package com.opsassistant.backend.audit;

import java.sql.Array;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.time.Instant;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.Arrays;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import lombok.RequiredArgsConstructor;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Repository;

/**
 * query_audit and query_feedback (migration V13). llm-service writes the audit rows; this side reads them for the
 * admin, records the asker's feedback, and clears the text the retention period is over for.
 *
 * Plain SQL rather than JPA entities: an audit row is never changed through an object, its arrays and JSON are read as
 * they are, and cross_department is generated by the database.
 */
@Repository
@RequiredArgsConstructor
public class QueryAuditRepository {

    private final JdbcClient jdbc;

    /** Who asked the question; empty when no question has this id. */
    public Optional<Long> askerOf(UUID queryId) {
        return jdbc.sql("SELECT user_id FROM query_audit WHERE query_id = :id").param("id", queryId)
                .query(Long.class).optional();
    }

    /** A second rating replaces the first, comment included. */
    public void saveFeedback(UUID queryId, String rating, String comment) {
        jdbc.sql("""
                INSERT INTO query_feedback (query_id, rating, comment) VALUES (:id, :rating, :comment)
                ON CONFLICT (query_id) DO UPDATE SET rating = EXCLUDED.rating, comment = EXCLUDED.comment, updated_at = now()
                """).param("id", queryId).param("rating", rating).param("comment", comment).update();
    }

    /** What the admin filters by; null: no filter. before: only rows older than this, for the next page. */
    public record Filter(Long userId, Boolean crossDepartment, OffsetDateTime before, int limit) {
    }

    /**
     * Newest first. The conditions are constants chosen here, the values parameters: cross_department as a constant
     * so its partial index is used whatever the plan.
     */
    public List<AuditEntry> list(Filter filter) {
        StringBuilder sql = new StringBuilder("""
                SELECT a.*, a.tokens::text AS tokens_json, a.timings_ms::text AS timings_json, f.rating, f.comment
                FROM query_audit a LEFT JOIN query_feedback f USING (query_id)
                WHERE true""");
        if (filter.userId() != null) {
            sql.append(" AND a.user_id = :userId");
        }
        if (filter.crossDepartment() != null) {
            sql.append(filter.crossDepartment() ? " AND a.cross_department" : " AND NOT a.cross_department");
        }
        if (filter.before() != null) {
            sql.append(" AND a.created_at < :before");
        }
        sql.append(" ORDER BY a.created_at DESC LIMIT :limit");
        var statement = jdbc.sql(sql.toString()).param("limit", filter.limit());
        if (filter.userId() != null) {
            statement = statement.param("userId", filter.userId());
        }
        if (filter.before() != null) {
            statement = statement.param("before", filter.before());
        }
        return statement.query((rs, n) -> entry(rs)).list();
    }

    /**
     * Clears the question, its rewrite and its SQL of up to batchSize rows older than the cutoff, oldest first; returns
     * how many. Rows another run has locked are skipped, so two backend instances never wait on each other.
     */
    public int clearTextBefore(Instant cutoff, int batchSize) {
        return jdbc.sql("""
                UPDATE query_audit SET question = NULL, rewritten = NULL, sql = NULL
                WHERE query_id IN (SELECT query_id FROM query_audit WHERE question IS NOT NULL AND created_at < :cutoff
                                   ORDER BY created_at LIMIT :batch FOR UPDATE SKIP LOCKED)
                """).param("cutoff", OffsetDateTime.ofInstant(cutoff, ZoneOffset.UTC)).param("batch", batchSize)
                .update();
    }

    /** The same for feedback comments, by when they were last written. */
    public int clearCommentsBefore(Instant cutoff, int batchSize) {
        return jdbc.sql("""
                UPDATE query_feedback SET comment = NULL
                WHERE query_id IN (SELECT query_id FROM query_feedback WHERE comment IS NOT NULL AND updated_at < :cutoff
                                   ORDER BY updated_at LIMIT :batch FOR UPDATE SKIP LOCKED)
                """).param("cutoff", OffsetDateTime.ofInstant(cutoff, ZoneOffset.UTC)).param("batch", batchSize)
                .update();
    }

    private static AuditEntry entry(ResultSet rs) throws SQLException {
        return new AuditEntry(
                rs.getObject("query_id", UUID.class), rs.getObject("created_at", OffsetDateTime.class).toInstant(),
                rs.getLong("user_id"), rs.getString("role"), rs.getString("department"),
                rs.getBoolean("cross_department"), rs.getObject("session_id", UUID.class), rs.getString("outcome"),
                rs.getString("cache_hit"), rs.getString("route"), rs.getString("decided_by"),
                rs.getObject("confidence", Float.class), strings(rs.getArray("paths")), strings(rs.getArray("cancelled")),
                rs.getString("written_by"), rs.getString("question"), rs.getString("rewritten"), rs.getString("sql"),
                rs.getObject("campaign_id", Long.class), rs.getObject("sql_attempts", Integer.class),
                rs.getObject("result_rows", Integer.class), longs(rs.getArray("cited_doc_ids")),
                rs.getObject("model_calls", Integer.class), rs.getObject("input_tokens", Integer.class),
                rs.getObject("output_tokens", Integer.class), rs.getString("tokens_json"),
                rs.getBigDecimal("cost_usd") == null ? null : rs.getBigDecimal("cost_usd").toPlainString(),
                rs.getInt("total_ms"), rs.getString("timings_json"), rs.getString("rating"), rs.getString("comment"));
    }

    private static List<String> strings(Array array) throws SQLException {
        return Arrays.asList((String[]) array.getArray());
    }

    private static List<Long> longs(Array array) throws SQLException {
        return Arrays.asList((Long[]) array.getArray());
    }
}
